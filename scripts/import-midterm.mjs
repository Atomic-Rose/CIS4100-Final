import { readFile, writeFile } from 'node:fs/promises';

const file = process.argv[2];
if (!file) throw new Error('Usage: npm run import:midterm -- path/to/question-bank.json');

const topics = [
  'Computers and systems', 'Systems and architecture', 'Number systems',
  'Data formats', 'Numeric representation', 'Little Man Computer',
];
const source = JSON.parse(await readFile(file, 'utf8'));
if (!Array.isArray(source) || !source.length) throw new Error('Expected a nonempty legacy question bank.');

const ids = new Set();
const questions = source.map(question => {
  const { id, chapter, topic, statement, answer, explanation, correction, steps, sources } = question;
  if (!Number.isInteger(chapter) || chapter < 1 || chapter > topics.length ||
      typeof id !== 'string' || !new RegExp(`^C${chapter}-[0-9]+$`).test(id) || ids.has(id) ||
      typeof answer !== 'boolean' || ![topic, statement, explanation].every(value => typeof value === 'string' && value.trim())) {
    throw new Error(`Invalid or duplicate legacy question: ${id}`);
  }
  ids.add(id);

  return {
    id, chapter, topic, type: 'true-false',
    prompt: statement, choices: ['True', 'False'], answer: answer ? 0 : 1,
    explanation: [explanation, correction, steps].filter(value => typeof value === 'string' && value.trim()).join(' '),
    reference: Array.isArray(sources) ? sources.filter(s => s?.file && s?.location).map(s => `${s.file} (${s.location})`).join(' · ') : '',
  };
});
const chapters = topics.map((title, index) => ({
  number: index + 1, title, subtitle: 'Midterm archive',
})).filter(chapter => questions.some(q => q.chapter === chapter.number));

const output = `// Generated by npm run import:midterm.\nexport const archiveChapters = ${JSON.stringify(chapters, null, 2)};\nexport const archiveQuestions = ${JSON.stringify(questions, null, 2)};\n`;
await writeFile(new URL('../src/data/archive.js', import.meta.url), output);
console.log(`Imported ${questions.length} midterm questions across ${chapters.length} chapters.`);
